-- Sunflower / CloudBase PostgreSQL / 新建测试环境
-- 整段执行。创建空表，不导入本地演示数据，不向小程序客户端开放直连权限。
begin;

create table public.accounts (
    id uuid primary key default gen_random_uuid(),
    wechat_appid text not null,
    wechat_openid text not null,
    role text not null check (role in ('interpreter', 'business')),
    status text not null default 'active' check (status in ('active', 'disabled')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (wechat_appid, wechat_openid),
    unique (id, role)
);

create table public.profiles (
    id bigint generated by default as identity primary key,
    owner_id uuid not null unique,
    role text not null,
    name text not null check (btrim(name) <> ''),
    phone text not null default '',
    school text not null default '',
    major text not null default '',
    english_level text not null default '',
    price_per_day numeric(12,2) not null default 0 check (price_per_day >= 0),
    campus_name text not null default '',
    campus_lat double precision check (campus_lat between -90 and 90),
    campus_lng double precision check (campus_lng between -180 and 180),
    intro text not null default '',
    company text not null default '',
    contact text not null default '',
    skills text not null default '',
    is_demo boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (owner_id, role) references public.accounts (id, role),
    check ((campus_lat is null) = (campus_lng is null))
);

create table public.availability (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references public.accounts (id),
    avail_date date not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (owner_id, avail_date)
);
create index availability_by_date on public.availability (avail_date, owner_id);

create table public.jobs (
    id bigint generated by default as identity primary key,
    business_id uuid not null references public.accounts (id),
    business_name text not null,
    title text not null check (btrim(title) <> ''),
    requirements text not null check (btrim(requirements) <> ''),
    service_date date not null,
    start_time time(0) not null,
    hours numeric(5,2) not null check (hours > 0 and hours <= 24),
    slots smallint not null check (slots between 1 and 100),
    rate numeric(12,2) not null check (rate >= 1),
    pay_unit text not null check (pay_unit in ('hour', 'half', 'day')),
    travel_allowance numeric(12,2) not null default 0 check (travel_allowance >= 0),
    total numeric(12,2) generated always as
        (round(rate * case when pay_unit = 'hour' then hours else 1 end + travel_allowance, 2)) stored,
    location_name text not null check (btrim(location_name) <> ''),
    location_address text not null default '',
    location_lat double precision check (location_lat between -90 and 90),
    location_lng double precision check (location_lng between -180 and 180),
    required_skills text not null default '',
    terms text not null default '',
    status text not null default 'open' check (status in ('open', 'closed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check ((location_lat is null) = (location_lng is null)),
    check (extract(epoch from start_time) + hours * 3600 <= 86400)
);
create index jobs_by_business on public.jobs (business_id, created_at desc);
create index jobs_open_by_date on public.jobs (service_date, start_time) where status = 'open';

create table public.orders (
    id bigint generated by default as identity primary key,
    business_id uuid not null references public.accounts (id),
    business_name text not null,
    interpreter_id uuid not null references public.accounts (id),
    interpreter_name text not null,
    service_date date not null,
    start_time time(0) not null,
    requirements text not null default '',
    required_skills text not null default '',
    location_name text not null default '',
    location_address text not null default '',
    location_lat double precision check (location_lat between -90 and 90),
    location_lng double precision check (location_lng between -180 and 180),
    price numeric(12,2) not null check (price > 0),
    deposit numeric(12,2) not null check (deposit >= 0 and deposit <= price),
    status text not null default 'pending'
        check (status in ('pending', 'accepted', 'deposit_paid', 'completed', 'finished', 'cancelled')),
    deposit_paid_at timestamptz,
    final_paid_at timestamptz,
    cancel_reason text not null default '',
    cancelled_by_role text check (cancelled_by_role in ('business', 'interpreter', 'system')),
    refund_status text not null default 'none' check (refund_status in ('none', 'pending', 'done')),
    refund_amount numeric(12,2) check (refund_amount >= 0 and refund_amount <= deposit),
    refunded_at timestamptz,
    rescheduled_from date,
    rescheduled_at timestamptz,
    job_id bigint references public.jobs (id),
    job_hours numeric(5,2) check (job_hours > 0 and job_hours <= 24),
    job_pay_unit text check (job_pay_unit in ('hour', 'half', 'day')),
    job_rate numeric(12,2) check (job_rate >= 0),
    job_terms text not null default '',
    job_travel_allowance numeric(12,2) not null default 0 check (job_travel_allowance >= 0),
    actual_hours numeric(5,2) check (actual_hours > 0 and actual_hours <= 24),
    hours_confirmed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (business_id <> interpreter_id),
    check ((location_lat is null) = (location_lng is null)),
    check (job_id is null or (job_hours is not null and job_pay_unit is not null and job_rate is not null)),
    check (hours_confirmed_at is null or actual_hours is not null),
    unique (id, job_id, interpreter_id)
);
create unique index orders_one_active_day on public.orders (interpreter_id, service_date)
    where status in ('pending', 'accepted', 'deposit_paid', 'completed');
create index orders_by_business on public.orders (business_id, updated_at desc);
create index orders_by_interpreter on public.orders (interpreter_id, updated_at desc);
create index orders_by_job on public.orders (job_id) where job_id is not null;

create table public.applications (
    id bigint generated by default as identity primary key,
    job_id bigint not null references public.jobs (id),
    interpreter_id uuid not null references public.accounts (id),
    interpreter_name text not null,
    status text not null default 'applied'
        check (status in ('applied', 'withdrawn', 'hired', 'rejected', 'full', 'closed')),
    order_id bigint unique,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (order_id, job_id, interpreter_id) references public.orders (id, job_id, interpreter_id),
    check ((status = 'hired') = (order_id is not null))
);
create unique index applications_one_current on public.applications (job_id, interpreter_id)
    where status <> 'withdrawn';
create index applications_by_interpreter on public.applications (interpreter_id, created_at desc);
create index applications_by_job_status on public.applications (job_id, status);

create table public.reviews (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders (id),
    reviewer_id uuid not null,
    reviewer_role text not null,
    reviewer_name text not null default '',
    target_id uuid not null,
    target_role text not null,
    rating smallint not null check (rating between 1 and 5),
    comment text not null default '',
    created_at timestamptz not null default now(),
    foreign key (reviewer_id, reviewer_role) references public.accounts (id, role),
    foreign key (target_id, target_role) references public.accounts (id, role),
    check (reviewer_id <> target_id and reviewer_role <> target_role),
    unique (order_id, reviewer_id)
);
create index reviews_by_target on public.reviews (target_id, created_at desc);

create table public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null,
    role text not null,
    type text not null default 'order',
    order_id bigint references public.orders (id),
    title text not null,
    body text not null default '',
    read smallint not null default 0 check (read in (0, 1)),
    created_at timestamptz not null default now(),
    foreign key (user_id, role) references public.accounts (id, role)
);
create index notifications_by_user on public.notifications (user_id, created_at desc);
create index notifications_unread on public.notifications (user_id) where read = 0;

create table public.settlements (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.accounts (id),
    amount numeric(12,2) not null check (amount > 0),
    status text not null default 'pending' check (status in ('pending', 'done', 'failed')),
    paid_at timestamptz,
    created_at timestamptz not null default now()
);
create index settlements_by_user on public.settlements (user_id, created_at desc);

create table public.favorites (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.accounts (id),
    target_id uuid not null references public.accounts (id),
    created_at timestamptz not null default now(),
    check (user_id <> target_id),
    unique (user_id, target_id)
);

create table public.job_safety (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('report', 'dispute', 'block')),
    user_id uuid not null references public.accounts (id),
    role text,
    business_id uuid references public.accounts (id),
    job_id bigint references public.jobs (id),
    order_id bigint references public.orders (id),
    detail text not null default '',
    status text not null default 'pending' check (status in ('pending', 'resolved', 'dismissed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (user_id, role) references public.accounts (id, role),
    check (
        (kind = 'block' and business_id is not null and job_id is null and order_id is null)
        or (kind = 'report' and job_id is not null and order_id is null and btrim(detail) <> '')
        or (kind = 'dispute' and job_id is not null and order_id is not null and btrim(detail) <> '')
    )
);
create unique index job_safety_one_block on public.job_safety (user_id, business_id) where kind = 'block';
create index job_safety_queue on public.job_safety (status, created_at) where kind <> 'block';

-- 创建后仅由受信任的服务端访问。给客户端开放前，另行设计最小授权与 RLS 策略。
do $sunflower$
declare
    table_name text;
    client_role text;
begin
    foreach table_name in array array[
        'accounts','profiles','availability','jobs','orders','applications',
        'reviews','notifications','settlements','favorites','job_safety'
    ] loop
        execute format('alter table public.%I enable row level security', table_name);
        execute format('revoke all on table public.%I from PUBLIC', table_name);
        foreach client_role in array array['anon','authenticated'] loop
            if exists (select 1 from pg_catalog.pg_roles where rolname = client_role) then
                execute format('revoke all on table public.%I from %I', table_name, client_role);
            end if;
        end loop;
    end loop;
end;
$sunflower$;

create function public.sunflower_touch_updated_at() returns trigger
language plpgsql set search_path = pg_catalog
as $sunflower$
begin
    new.updated_at := now();
    return new;
end;
$sunflower$;

create trigger accounts_touch before update on public.accounts
    for each row execute function public.sunflower_touch_updated_at();
create trigger profiles_touch before update on public.profiles
    for each row execute function public.sunflower_touch_updated_at();
create trigger availability_touch before update on public.availability
    for each row execute function public.sunflower_touch_updated_at();
create trigger jobs_touch before update on public.jobs
    for each row execute function public.sunflower_touch_updated_at();
create trigger orders_touch before update on public.orders
    for each row execute function public.sunflower_touch_updated_at();
create trigger applications_touch before update on public.applications
    for each row execute function public.sunflower_touch_updated_at();
create trigger job_safety_touch before update on public.job_safety
    for each row execute function public.sunflower_touch_updated_at();

commit;
